const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      return window.localStorage.getItem(STORAGE_KEY) === 'am' ? 'am' : 'en';
    } catch {
      return 'en';
    }
  });

  function setLanguage(nextLanguage) {
    if (nextLanguage !== 'en' && nextLanguage !== 'am') {
      throw new TypeError('Language must be English or Amharic.');
    }
    try {
      window.localStorage.setItem(STORAGE_KEY, nextLanguage);
    } catch (error) {
      console.error('Unable to save language preference:', error);
    }
    setLanguageState(nextLanguage);
  }

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => language === 'am' ? (translations.am[text] ?? text) : text,
  }), [language]);

  useEffect(() => {
    document.documentElement.lang = language === 'am' ? 'am' : 'en';
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider.');
  return context;
}

export function LanguageSwitcher({ className = '' }) {
  const { language, setLanguage } = useLanguage();
  return (
    <div className={`language-switcher ${className}`.trim()} role='group' aria-label='Language / ቋንቋ'>
      <button type='button' onClick={() => setLanguage('en')} className={language === 'en' ? 'active' : ''} aria-pressed={language === 'en'}>EN</button>
      <button type='button' onClick={() => setLanguage('am')} className={language === 'am' ? 'active' : ''} aria-pressed={language === 'am'}>AM</button>
    </div>
  );
}
